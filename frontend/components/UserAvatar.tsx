const DEFAULT_PATH = "M16 7a4 4 0 11-8 0 4 4 0 018 0zM12 14a7 7 0 00-7 7h14a7 7 0 00-7-7z";

/** Lê o avatar ID salvo no localStorage */
export function getAvatarId(): string {
  if (typeof window === "undefined") return "";
  return localStorage.getItem("controllo_avatar") ?? "";
}

/** Componente de avatar que lê automaticamente do localStorage */
export function UserAvatar({ size = 32, className = "" }: { size?: number; className?: string }) {
  const [avatarId, setAvatarId] = useState("");

  useEffect(() => {
    setAvatarId(getAvatarId());
    // Re-check when storage changes (e.g., after saving in configuracoes)
    const handler = () => setAvatarId(getAvatarId());
    window.addEventListener("storage", handler);
    // Also poll for same-tab changes
    const interval = setInterval(handler, 2000);
    return () => { window.removeEventListener("storage", handler); clearInterval(interval); };
  }, []);

  const pathData = FLAT_PATHS[avatarId] ?? DEFAULT_PATH;
  const iconSize = Math.max(14, Math.round(size * 0.55));

  return (
    <div
      className={`flex items-center justify-center flex-shrink-0 ${className}`}
      style={{
        width: size, height: size,
        borderRadius: size > 28 ? 12 : 8,
        background: avatarId
          ? "linear-gradient(135deg, var(--brand-accent, rgba(30,73,118,0.15)), rgba(59,110,165,0.08))"
          : "rgba(100,116,139,0.12)",
        border: `1px solid var(--border, rgba(100,116,139,0.2))`,
      }}
    >
      <svg
        style={{ width: iconSize, height: iconSize, color: "var(--text-secondary, #94a3b8)" }}
        fill="none"
        viewBox="0 0 24 24"
        stroke="currentColor"
        strokeWidth={1.8}
      >
        <path strokeLinecap="round" strokeLinejoin="round" d={pathData} />
      </svg>
    </div>
  );
}
